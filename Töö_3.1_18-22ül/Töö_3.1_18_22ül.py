#20. Сумма чисел, которые делятся на 5 или 7
summa = 0 # Начальная сумма

for i in range(1,51): # Перебираем числа от 1 до 50
    if i % 5 == 0 or i % 7 == 0: # Проверяем деление на 5 или 7
        summa += i # Добавляем число к сумме
